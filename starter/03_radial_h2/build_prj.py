"""Write the OGS project file (.prj) for cyclic H2 storage around one well.

Model: TH2M process (isothermal use), 2D axisymmetric (r, z), one closed
reservoir layer, H2 as the only gas component, brine as the liquid.
All numbers come from ../properties/properties.csv.

Trapping bracket (OGS has no hysteresis):
  --bracket drainage    residual gas saturation 0 (no trapping, best case)
  --bracket imbibition  residual gas saturation from Land (1968) everywhere
                        (maximum trapping, worst case)

Usage:
  python build_prj.py --bracket drainage            -> radial_drainage.prj
  python build_prj.py --bracket imbibition
  python build_prj.py --set rate_inj=0.2 --tag q02  -> sensitivity variant
"""
import argparse
import sys
from pathlib import Path

here = Path(__file__).resolve().parent
sys.path.insert(0, str(here.parent / "common"))
import props  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("--bracket", choices=["drainage", "imbibition"], default="drainage")
ap.add_argument("--set", nargs="*", default=[], help="override, e.g. rate_inj=0.2")
ap.add_argument("--tag", default="", help="extra name tag for sensitivity runs")
ap.add_argument("--gravity", action="store_true", help="switch gravity on")
ap.add_argument("--cycles", type=int, default=None, help="override n_cycles")
a = ap.parse_args()
P = props.load(a.set)
if a.cycles:
    P["n_cycles"] = a.cycles

DAY = 86400.0
S_Lr = P["res_S_Lr"]
if a.bracket == "drainage":
    S_gr = P["res_S_gr_drain"]
else:  # Land-type trapped gas saturation from the largest possible gas saturation
    S_gr = props.land_trapped(1.0 - S_Lr, P["land_C"])
pc0 = props.vg_pc(P["S_L_init"], P["res_vG_pb"], P["res_vG_m"], S_Lr, S_gr)

import pyvista as pv  # noqa: E402
import schedule  # noqa: E402

# Neumann flux on the well face: H2 mass flux [kg/(m2 s)] = rate / (2 pi r_w H)
# (OGS integrates axisymmetric boundaries over 2 pi r; postprocess.py checks
#  this with a mass balance)
well = pv.read(here / "mesh" / "well.vtu")
r_w = well.bounds[0]
H = well.bounds[3] - well.bounds[2]
q = P["rate_inj"] / (2 * 3.141592653589793 * r_w * H)
S = schedule.build(P, q)
t_end, coords, values = S["t_end"], S["coords"], S["values"]
dirichlet_wd = schedule.dirichlet_windows_xml(S, "well", "p_bhp_min")
fixed_times = schedule.output_times(S)
g = "0 -9.81" if a.gravity else "0 0"
name = f"radial_{a.bracket}{('_' + a.tag) if a.tag else ''}"
axi = 'axially_symmetric="true"'


def prop(n, typ, body):
    return f"<property><name>{n}</name><type>{typ}</type>{body}</property>"


def const(n, v):
    return prop(n, "Constant", f"<value>{v}</value>")


prj = f"""<?xml version="1.0" encoding="ISO-8859-1"?>
<!-- Generated by build_prj.py from properties.csv. bracket={a.bracket}, S_gr={S_gr:.4f}, pc0={pc0:.1f} Pa -->
<OpenGeoSysProject>
    <meshes>
        <mesh {axi}>mesh/domain.vtu</mesh>
        <mesh {axi}>mesh/well.vtu</mesh>
        <mesh {axi}>mesh/outer.vtu</mesh>
        <mesh {axi}>mesh/bottom.vtu</mesh>
    </meshes>
    <processes>
        <process>
            <name>TH2M</name>
            <type>TH2M</type>
            <integration_order>2</integration_order>
            <constitutive_relation>
                <type>LinearElasticIsotropic</type>
                <youngs_modulus>E</youngs_modulus>
                <poissons_ratio>nu</poissons_ratio>
            </constitutive_relation>
            <jacobian_assembler>
                <type>CentralDifferences</type>
                <epsilons>0.01 0.01 1e-06</epsilons>
            </jacobian_assembler>
            <process_variables>
                <gas_pressure>gas_pressure</gas_pressure>
                <capillary_pressure>capillary_pressure</capillary_pressure>
                <temperature>temperature</temperature>
                <displacement>displacement</displacement>
            </process_variables>
            <secondary_variables>
                <secondary_variable name="sigma"/>
                <secondary_variable name="epsilon"/>
                <secondary_variable name="gas_density"/>
                <secondary_variable name="liquid_density"/>
                <secondary_variable name="porosity"/>
                <secondary_variable name="saturation"/>
                <secondary_variable name="velocity_gas"/>
                <secondary_variable internal_name="mass_fraction_liquid" output_name="xmWL"/>
            </secondary_variables>
            <specific_body_force>{g}</specific_body_force>
            <mass_lumping>false</mass_lumping>
        </process>
    </processes>
    <media>
        <medium>
            <phases>
                <phase>
                    <type>AqueousLiquid</type>
                    <components>
                        <component>
                            <name>H2</name>
                            <properties>
                                {const("specific_heat_capacity", 14300)}
                                {const("henry_coefficient", P["H2_henry"])}
                                {const("diffusion", P["H2_diff_liquid"])}
                                {const("specific_latent_heat", 0)}
                            </properties>
                        </component>
                        <component>
                            <name>W</name>
                            <properties>
                                {const("specific_heat_capacity", 4187)}
                            </properties>
                        </component>
                    </components>
                    <properties>
                        {const("thermal_conductivity", 0.6)}
                        {prop("density", "Linear", f'''<reference_value>{P["brine_density"]}</reference_value>
                            <independent_variable><variable_name>liquid_phase_pressure</variable_name>
                            <reference_condition>{P["p_init"]}</reference_condition>
                            <slope>{P["brine_compressibility"]}</slope></independent_variable>
                            <independent_variable><variable_name>concentration</variable_name>
                            <reference_condition>0</reference_condition>
                            <slope>{P["H2_M"] / P["brine_density"]:.6e}</slope></independent_variable>''')}
                        <!-- the concentration term is what carries dissolved H2 mass in TH2M:
                             rho_L = rho_ref (1 + beta (p_L - p_ref) + (M_H2/rho_ref) c_H2) -->
                        {const("viscosity", P["brine_viscosity"])}
                    </properties>
                </phase>
                <phase>
                    <type>Gas</type>
                    <components>
                        <component>
                            <name>H2</name>
                            <properties>
                                {const("molar_mass", P["H2_M"])}
                                {const("specific_heat_capacity", 14300)}
                            </properties>
                        </component>
                        <component>
                            <name>W</name>
                            <properties>
                                {const("molar_mass", 0.018015)}
                                {const("specific_heat_capacity", 2000)}
                                {const("specific_latent_heat", 0)}
                                {const("vapour_pressure", 0.0)}
                                {const("diffusion", 0.0)}
                            </properties>
                        </component>
                    </components>
                    <properties>
                        {const("thermal_conductivity", 0.2)}
                        <!-- Ideal gas (H2 + vapour). PengRobinson is not usable here: OGS 6.5.9 TH2M
                             with phase transition needs derivatives the PengRobinson type does not provide.
                             Density error vs. reference EOS: see properties/h2_properties_check.txt -->
                        {prop("density", "IdealGasLawBinaryMixture", "")}
                        {const("viscosity", P["H2_viscosity"])}
                    </properties>
                </phase>
                <phase>
                    <type>Solid</type>
                    <properties>
                        {const("density", P["rho_solid"])}
                        {const("thermal_conductivity", 3.0)}
                        {const("specific_heat_capacity", 800)}
                        {const("thermal_expansivity", 0)}
                    </properties>
                </phase>
            </phases>
            <properties>
                {const("permeability", P["res_permeability"])}
                {const("porosity", P["res_porosity"])}
                {const("biot_coefficient", P["biot"])}
                {const("tortuosity", 1)}
                {prop("saturation", "SaturationVanGenuchten", f'''<residual_liquid_saturation>{S_Lr}</residual_liquid_saturation>
                    <residual_gas_saturation>{S_gr}</residual_gas_saturation>
                    <p_b>{P["res_vG_pb"]}</p_b><exponent>{P["res_vG_m"]}</exponent>''')}
                {prop("relative_permeability", "RelativePermeabilityVanGenuchten", f'''<residual_liquid_saturation>{S_Lr}</residual_liquid_saturation>
                    <residual_gas_saturation>{S_gr}</residual_gas_saturation><exponent>{P["res_vG_m"]}</exponent>
                    <minimum_relative_permeability_liquid>1e-12</minimum_relative_permeability_liquid>''')}
                {prop("relative_permeability_nonwetting_phase", "RelativePermeabilityNonWettingPhaseVanGenuchtenMualem", f'''<residual_liquid_saturation>{S_Lr}</residual_liquid_saturation>
                    <residual_gas_saturation>{S_gr}</residual_gas_saturation><exponent>{P["res_vG_m"]}</exponent>
                    <min_relative_permeability>1e-9</min_relative_permeability>''')}
                {prop("thermal_conductivity", "EffectiveThermalConductivityPorosityMixing", "")}
                {prop("bishops_effective_stress", "BishopsPowerLaw", "<exponent>1</exponent>")}
            </properties>
        </medium>
    </media>
    <time_loop>
        <processes>
            <process ref="TH2M">
                <nonlinear_solver>basic_newton</nonlinear_solver>
                <convergence_criterion>
                    <type>PerComponentDeltaX</type>
                    <norm_type>NORM2</norm_type>
                    <abstols>1e-1 1e-1 1e-5 1e-8 1e-8</abstols>
                </convergence_criterion>
                <time_discretization><type>BackwardEuler</type></time_discretization>
                <time_stepping>
                    <type>IterationNumberBasedTimeStepping</type>
                    <t_initial>0</t_initial>
                    <t_end>{t_end:.1f}</t_end>
                    <initial_dt>60</initial_dt>
                    <minimum_dt>1</minimum_dt>
                    <maximum_dt>{2 * DAY:.0f}</maximum_dt>
                    <number_iterations>2 4 8 12 20</number_iterations>
                    <multiplier>1.6 1.3 1.0 0.7 0.5</multiplier>
                </time_stepping>
            </process>
        </processes>
        <output>
            <type>VTK</type>
            <prefix>{name}</prefix>
            <suffix>_t_{{:gtime}}</suffix>
            <timesteps><pair><repeat>1</repeat><each_steps>100000000</each_steps></pair></timesteps>
            <variables>
                <variable>gas_pressure</variable>
                <variable>capillary_pressure</variable>
                <variable>displacement</variable>
                <variable>sigma</variable>
                <variable>epsilon</variable>
                <variable>gas_density</variable>
                <variable>liquid_density</variable>
                <variable>porosity</variable>
                <variable>saturation</variable>
                <variable>velocity_gas</variable>
                <variable>xmWL</variable>
            </variables>
            <fixed_output_times>{" ".join(f"{x:.1f}" for x in fixed_times)}</fixed_output_times>
        </output>
    </time_loop>
    <parameters>
        <parameter><name>E</name><type>Constant</type><value>{P["res_E"]}</value></parameter>
        <parameter><name>nu</name><type>Constant</type><value>{P["res_nu"]}</value></parameter>
        <parameter><name>zero</name><type>Constant</type><value>0</value></parameter>
        <parameter><name>u0</name><type>Constant</type><values>0 0</values></parameter>
        <parameter><name>T0</name><type>Constant</type><value>{P["T_res"]}</value></parameter>
        <parameter><name>pg0</name><type>Constant</type><value>{P["p_init"]}</value></parameter>
        <parameter><name>pc0</name><type>Constant</type><value>{pc0:.3f}</value></parameter>
        <parameter><name>p_bhp_min</name><type>Constant</type><value>{P["p_bhp_min"]}</value></parameter>
        <parameter><name>one</name><type>Constant</type><value>1</value></parameter>
        <parameter><name>h2_flux</name><type>CurveScaled</type><curve>injection_schedule</curve><parameter>one</parameter></parameter>
    </parameters>
    <curves>
        <curve>
            <name>injection_schedule</name>
            <coords>{" ".join(f"{c:.1f}" for c in coords)}</coords>
            <values>{" ".join(f"{v:.6e}" for v in values)}</values>
        </curve>
    </curves>
    <process_variables>
        <process_variable>
            <name>displacement</name><components>2</components><order>1</order>
            <initial_condition>u0</initial_condition>
            <boundary_conditions>
                <boundary_condition><mesh>bottom</mesh><type>Dirichlet</type><component>1</component><parameter>zero</parameter></boundary_condition>
                <boundary_condition><mesh>outer</mesh><type>Dirichlet</type><component>0</component><parameter>zero</parameter></boundary_condition>
                <boundary_condition><mesh>well</mesh><type>Dirichlet</type><component>0</component><parameter>zero</parameter></boundary_condition>
            </boundary_conditions>
        </process_variable>
        <process_variable>
            <name>gas_pressure</name><components>1</components><order>1</order>
            <initial_condition>pg0</initial_condition>
            <boundary_conditions>
                <boundary_condition><mesh>well</mesh><type>Neumann</type><component>0</component><parameter>h2_flux</parameter></boundary_condition>{dirichlet_wd}
            </boundary_conditions>
        </process_variable>
        <process_variable>
            <name>capillary_pressure</name><components>1</components><order>1</order>
            <initial_condition>pc0</initial_condition>
        </process_variable>
        <process_variable>
            <name>temperature</name><components>1</components><order>1</order>
            <initial_condition>T0</initial_condition>
            <boundary_conditions>
                <boundary_condition><mesh>domain</mesh><type>Dirichlet</type><component>0</component><parameter>T0</parameter></boundary_condition>
            </boundary_conditions>
        </process_variable>
    </process_variables>
    <nonlinear_solvers>
        <nonlinear_solver><name>basic_newton</name><type>Newton</type><max_iter>25</max_iter><linear_solver>direct</linear_solver></nonlinear_solver>
    </nonlinear_solvers>
    <linear_solvers>
        <linear_solver><name>direct</name><eigen><solver_type>SparseLU</solver_type><scaling>true</scaling></eigen></linear_solver>
    </linear_solvers>
</OpenGeoSysProject>
"""
out = here / f"{name}.prj"
out.write_text(prj)
print(f"wrote {out.name}: S_gr={S_gr:.3f}, pc0={pc0/1e3:.1f} kPa, q={q:.4e} kg/m2/s, "
      f"t_end={t_end/DAY:.0f} d, {len(fixed_times)} output times")
